// Packs PixelLab character animations into horizontal sprite sheets and writes the sprite manifest.
// Every frame of a character (static pose + all animations) is cropped to one shared square box,
// so swapping between still and animated sprites never shifts the character. Only free GET calls.
//   node --env-file=.env scripts/pack-sprites.mjs
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const KEY = process.env.PIXELLAB_API_KEY;
const API = "https://api.pixellab.ai/v2";
const DIR = path.resolve("public/assets/characters");
const state = JSON.parse(await fs.readFile(path.resolve("scripts/.pixellab-state.json"), "utf8"));

const NAMES = { "breathing-idle": "idle", walking: "walk", "two-footed-jump": "jump" };
const SPEED = { idle: 220, walk: 120, jump: 110 };

const fetchPng = async (url) => Buffer.from(await (await fetch(url)).arrayBuffer());
async function bbox(buf) {
  const { data, info } = await sharp(buf).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let x0 = info.width, y0 = info.height, x1 = -1, y1 = -1;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    if (data[(y * info.width + x) * 4 + 3] > 8) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); }
  }
  return { x0, y0, x1, y1, w: info.width, h: info.height };
}

const manifest = {};
for (const [key, s] of Object.entries(state)) {
  if (!key.startsWith("char:") || !s.id) continue;
  const name = key.slice(5);
  const res = await fetch(`${API}/characters/${s.id}`, { headers: { Authorization: `Bearer ${KEY}` } });
  if (!res.ok) { console.error("skip", name, res.status); continue; }
  const c = await res.json();
  if (!c.rotation_urls?.south) { console.error("not ready", name); continue; }
  const still = await fetchPng(c.rotation_urls.south);
  const anims = {};
  for (const g of c.animations ?? []) {
    const short = NAMES[g.animation_type] ?? NAMES[g.display_name];
    const dir = g.directions?.find((d) => d.direction === "south");
    if (!short || !dir?.frames?.length) continue;
    anims[short] = await Promise.all(dir.frames.map(fetchPng));
  }
  // Shared crop box across the still and every frame, squared, feet on the bottom edge.
  const boxes = await Promise.all([still, ...Object.values(anims).flat()].map(bbox));
  const x0 = Math.min(...boxes.map((b) => b.x0)), y0 = Math.min(...boxes.map((b) => b.y0));
  const x1 = Math.max(...boxes.map((b) => b.x1)), y1 = Math.max(...boxes.map((b) => b.y1));
  const side = Math.max(x1 - x0 + 1, y1 - y0 + 1) + 2;
  const left = Math.max(0, Math.round((x0 + x1 + 1) / 2 - side / 2));
  const top = Math.max(0, y1 + 1 - side + 1);
  const crop = async (buf) => {
    const { w, h } = await bbox(buf);
    const ext = { left: Math.min(left, w - 1), top: Math.min(top, h - 1) };
    const width = Math.min(side, w - ext.left), height = Math.min(side, h - ext.top);
    return sharp(buf).extract({ ...ext, width, height }).extend({ right: side - width, bottom: side - height, background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer();
  };
  await fs.writeFile(path.join(DIR, `${name}.png`), await crop(still));
  manifest[name] = { size: side, anims: {} };
  for (const [short, frames] of Object.entries(anims)) {
    const cropped = await Promise.all(frames.map(crop));
    await sharp({ create: { width: side * frames.length, height: side, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
      .composite(cropped.map((input, i) => ({ input, left: i * side, top: 0 })))
      .png().toFile(path.join(DIR, `${name}-${short}.png`));
    manifest[name].anims[short] = { frames: frames.length, ms: SPEED[short] };
  }
  console.log("packed", name, side, Object.keys(manifest[name].anims).join(",") || "(still)");
}

// Merge with the existing manifest so characters packed earlier keep their entries.
const out = path.resolve("src/lib/pixel/sprites.ts");
let prev = {};
try { prev = JSON.parse((await fs.readFile(out, "utf8")).match(/= (\{[\s\S]*\});/)[1]); } catch {}
const merged = { ...prev, ...manifest };
await fs.writeFile(out, `// Generated by scripts/pack-sprites.mjs. Do not edit by hand.\nexport type SpriteAnim = "idle" | "walk" | "jump";\nexport const SPRITES: Record<string, { size: number; anims: Partial<Record<SpriteAnim, { frames: number; ms: number }>> }> = ${JSON.stringify(merged, null, 2)};\n`);
console.log("manifest", Object.keys(merged).length, "characters");
