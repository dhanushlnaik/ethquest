// Builds the ETHQuest mark from the official EIPsInsight mark (eipsinsight-v4/public/brand/logov2/mark-white.png):
// the rising bars + zig-zag arrow, redrawn as treasure: bars become stacked gold coins on a parchment compass
// medallion, and the arrow is the red quest path breaking out of the frame. Outputs SVG + PNGs + PWA icons.
//   pnpm tsx scripts/gen-logo.ts
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const N = 32;
const INK = "#1f140b";

async function main() {
  const grid: string[][] = Array.from({ length: N }, () => Array(N).fill(""));
  const set = (x: number, y: number, c: string) => { if (x >= 0 && y >= 0 && x < N && y < N) grid[y][x] = c; };
  const on = (x: number, y: number) => x >= 0 && y >= 0 && x < N && y < N && grid[y][x] !== "";

  // Compass medallion: wooden ring with brass rivets at N/E/S/W, parchment disc inside.
  const C = 15.5;
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
    const d = Math.hypot(x - C, y - C);
    if (d <= 15) set(x, y, d > 12.6 ? ((x + y) % 3 ? "#7a4b29" : "#6b4325") : d > 11.6 ? "#b8860b" : "#ead9b4");
  }
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
    const d = Math.hypot(x - C, y - C);
    if (d <= 11.6 && d > 10.6 && y < C) set(x, y, "#f7ecd2"); // disc highlight
  }
  for (const [x, y] of [[15, 1], [16, 1], [15, 30], [16, 30], [1, 15], [1, 16], [30, 15], [30, 16]]) set(x, y, "#f5c542");

  // Gold-coin bars (rising left → right), offset onto the disc.
  const OX = 4, OY = 3;
  const bars: [number, number, number][] = [[3, 5, 19], [7, 9, 15], [11, 13, 16], [15, 17, 11]];
  for (const [x0, x1, top] of bars) for (let x = x0; x <= x1; x++) for (let y = top; y <= 21; y++) {
    const coin = (21 - y) % 2 === 0 ? "#e0a400" : "#f5c542";
    set(x + OX, y + OY, x === x0 ? "#ffe89a" : x === x1 ? "#b8860b" : coin);
  }
  // Red quest arrow (2px brush): low-left → peak → dip → up and out past the rim.
  const ARROW = "#d9583f";
  const pts = [[1, 17], [7, 11], [10, 14], [18, 6]];
  for (let i = 0; i < pts.length - 1; i++) {
    const [x0, y0] = pts[i], [x1, y1] = pts[i + 1];
    const steps = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0));
    for (let t = 0; t <= steps; t++) {
      const x = Math.round(x0 + ((x1 - x0) * t) / steps), y = Math.round(y0 + ((y1 - y0) * t) / steps);
      set(x + OX, y + OY, ARROW); set(x + OX, y + OY + 1, ARROW);
    }
  }
  // Arrowhead: right triangle with its tip up-right of the shaft end, breaking out of the frame.
  const [ex, ey] = [pts[pts.length - 1][0] + OX, pts[pts.length - 1][1] + OY];
  const [tx, ty, L] = [ex + 5, ey - 6, 5];
  for (let y = ty; y <= ty + L; y++) for (let x = tx - L; x <= tx; x++) if (tx - x + (y - ty) <= L) set(x, y, ARROW);
  for (let t = 0; ex + t < tx - 1; t++) { set(ex + t, ey - t, ARROW); set(ex + t, ey - t + 1, ARROW); } // shaft into the head
  const isArrow = (x: number, y: number) => grid[y]?.[x] === ARROW;

  const rects: string[] = [];
  const px = (x: number, y: number, fill: string) => rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`);
  // outline everything
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
    if (on(x, y)) continue;
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) if (on(x + dx, y + dy)) { px(x, y, INK); break; }
  }
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
    if (!on(x, y)) continue;
    px(x, y, grid[y][x]);
    // ink keyline around the arrow wherever it crosses the disc or coins, so it reads as on top
    if (!isArrow(x, y) && [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => isArrow(x + dx, y + dy))) px(x, y, INK);
  }
  // treasure sparkle at the arrowhead
  for (const [x, y] of [[tx + 2, ty - 2], [tx + 1, ty - 1], [tx + 3, ty - 1], [tx + 2, ty]]) px(x, y, "#fff3d6");
  const svg = (bg: boolean) =>
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${N} ${N}" shape-rendering="crispEdges">${bg ? `<rect width="${N}" height="${N}" rx="6" fill="#2f4a48"/>` : ""}${rects.join("")}</svg>`;
  const out = path.resolve("public/assets/brand");
  await fs.mkdir(out, { recursive: true });
  await fs.writeFile(path.join(out, "ethquest-mark.svg"), svg(false));
  await fs.writeFile(path.join(out, "ethquest-mark-tile.svg"), svg(true));
  // React-friendly rect list for inline rendering
  await fs.writeFile(path.resolve("src/lib/pixel/mark.ts"), `// Generated by scripts/gen-logo.ts from the EIPsInsight mark. Do not edit by hand.\nexport const MARK_SIZE = ${N};\nexport const MARK_SVG_BODY = ${JSON.stringify(rects.join(""))};\n`);
  for (const size of [192, 512]) {
    const markPng = await sharp(Buffer.from(svg(false)), { density: 72 * Math.ceil((size * 0.68) / N) }).resize(Math.round(size * 0.68), Math.round(size * 0.68), { kernel: "nearest" }).png().toBuffer();
    const bgSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#3f6b6a"/><stop offset="1" stop-color="#24302f"/></linearGradient></defs><rect width="${size}" height="${size}" fill="url(#g)"/></svg>`;
    const icon = await sharp(Buffer.from(bgSvg)).composite([{ input: markPng, gravity: "center" }]).png().toBuffer();
    await fs.writeFile(path.resolve("public/icons", `icon-${size}.png`), icon);
    if (size === 512) {
      await fs.writeFile(path.resolve("public/icons/maskable-512.png"), icon);
      await fs.writeFile(path.join(out, "ethquest-mark-512.png"), markPng);
    }
  }
  await sharp(path.resolve("public/icons/icon-192.png")).resize(180, 180).png().toFile(path.resolve("public/icons/apple-touch-icon.png"));
  console.log("logo generated");
}
main();
