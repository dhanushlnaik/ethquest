export type IconName = keyof typeof ICONS;

export function iconRects(name: IconName) {
  const rows = ICONS[name];
  const rects: { x: number; y: number; fill: string }[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < 10; x++) {
      const ch = row[x];
      if (ch && ch !== "." && PIXEL_COLORS[ch]) rects.push({ x, y, fill: PIXEL_COLORS[ch] });
    }
  });
  return rects;
}

export function iconSvg(name: IconName, size = 40) {
  const body = iconRects(name)
    .map((r) => `<rect x="${r.x}" y="${r.y}" width="1" height="1" fill="${r.fill}"/>`)
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10" width="${size}" height="${size}" shape-rendering="crispEdges">${body}</svg>`;
}
